// اختبار نقل الملصقات إلى ترس المتابعة ونقل التحليل لتبويب سجل الأعمال
const { chromium } = require('playwright'); const fs=require('fs');
const MOCK = fs.readFileSync(__dirname+'/mock-firebase.js','utf8');
let FAIL=0, ERRS=0; const ok=(c,m)=>{ console.log((c?'  ✓ ':'  ✗ ')+m); if(!c) FAIL++; };
(async()=>{
  const b=await chromium.launch(); const ctx=await b.newContext({viewport:{width:420,height:820}});
  await ctx.route(/jsdelivr|cdnjs|googleapis|gstatic|opencv/, r=>{ if(/firebase-app-compat/.test(r.request().url())) return r.fulfill({status:200,contentType:'application/javascript',body:MOCK}); r.fulfill({status:200,contentType:'application/javascript',body:''}); });
  await ctx.addInitScript(()=>{ window.__mockUid='U_sa1'; localStorage.setItem('cls_session',JSON.stringify({userId:'sa1',username:'مدير',role:'schoolAdmin',schoolId:'S2',period:'first',ctxKey:'school:S2'})); localStorage.setItem('__mockdb',JSON.stringify({'schools/S2':{name:'م'},'users/sa1':{authUid:'U_sa1',active:true,role:'schoolAdmin',username:'مدير',schools:{S2:{role:'teacher'}}}})); });
  const p=await ctx.newPage(); p.on('pageerror',e=>{ ERRS++; console.log('PAGEERR',e.message); });
  await p.goto('http://127.0.0.1:8765/omr.html'); await p.waitForTimeout(2000);
  console.log('1. تبويب النتائج بلا شريط فرعي');
  await p.evaluate(()=>showTab('results'));
  ok(!(await p.locator('#resSubNav').count()),'لا شريط فرعي'); ok(await p.isVisible('#resListCard'),'سجل النتائج ظاهر'); ok(!(await p.isVisible('#resAnCard')),'التحليل ليس هنا');
  console.log('2. تبويب سجل الأعمال');
  await p.evaluate(()=>showTab('cloud'));
  ok(await p.isVisible('#cloudSubNav'),'شريط فرعي: سجل الأعمال | تحليل النتائج');
  ok(/إعداد سجل الأعمال/.test(await p.textContent('#panel-cloud h2')) && !/الملصقات/.test(await p.textContent('#panel-cloud h2')),'العنوان «إعداد سجل الأعمال» بلا ملصقات');
  ok(!(await p.locator('#cardStickers').count()) ,'لا قسم ملصقات داخل الإعداد');
  ok(await p.isVisible('#cloudLogWrap') && !(await p.isVisible('#resAnCard')),'يبدأ بسجل الأعمال');
  await p.click('#cloudSubAn'); ok(await p.isVisible('#resAnCard') && !(await p.isVisible('#cloudLogWrap')),'تحليل النتائج');
  await p.click('#cloudSubLog'); ok(await p.isVisible('#cloudLogWrap'),'رجوع');
  console.log('3. ترس الملصقات في المتابعة');
  await p.evaluate(()=>{ document.getElementById('followOv').classList.add('show'); });
  ok(await p.isVisible('#followOv .flx[title="إعداد الملصقات"]'),'الترس ظاهر في المتابعة');
  await p.click('#followOv .flx[title="إعداد الملصقات"]'); await p.waitForTimeout(200);
  ok(await p.isVisible('#omrModalOv #stickerSetupHost'),'تنبثق نافذة إعداد الملصقات');
  ok((await p.locator('#stickerSetupHost input').count())>3,'حقول الملصقات معروضة');
  await p.evaluate(()=>setStickerField(0,'name','اختبار ملصق')); await p.evaluate(()=>{ window.alert=()=>{}; saveStickers(); });
  ok((await p.evaluate(()=>state.stickers[0].name))==='اختبار ملصق','التعديل يُحفظ');
  await p.click('#omrModalOv button.ghost'); ok(!(await p.locator('#omrModalOv').count()),'تُغلق بزر ✕');
  await b.close(); console.log(FAIL||ERRS?`✗ فشل ${FAIL}/${ERRS}`:'✓ كل الاختبارات نجحت'); process.exit(FAIL||ERRS?1:0);
})();
